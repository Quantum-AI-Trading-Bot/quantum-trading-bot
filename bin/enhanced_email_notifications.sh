# Send alert on important events
send_alert() {
    local alert_type=$1
    local details=$2

    case $alert_type in
        "trading_signal")
            send_immediate_notification "🎯 New Trading Signal" "$details"
            ;;
        "error")
            send_immediate_notification "⚠️ Trading Bot Error" "$details"
            ;;
        "milestone")
            send_immediate_notification "🏆 Trading Milestone" "$details"
            ;;
        *)
            send_immediate_notification "ℹ️ Bot Notification" "$details"
            ;;
    esac
}

# EMAIL SENDING DISABLED - 2026-02-10
log "[EMAIL DISABLED] All email notifications are disabled."
exit 0

# Main menu
case "${1:-}" in
    "immediate")
        send_immediate_notification "${2:-Notification}" "${3:-Message}"
        ;;
    "daily")
        send_daily_summary
        ;;
    "weekly")
        send_weekly_report
        ;;
    "alert")
        send_alert "${2:-info}" "${3:-Details}"
        ;;
    "test")
        send_immediate_notification "Test Notification" "This is a test of the enhanced notification system"
        ;;
    *)
        echo "Usage: $0 {immediate|daily|weekly|alert|test}"
        echo ""
        echo "Commands:"
        echo "  immediate <subject> <message>  - Send immediate notification"
        echo "  daily                          - Send daily summary report"
        echo "  weekly                         - Send weekly performance report"
        echo "  alert <type> <details>         - Send alert (trading_signal/error/milestone)"
        echo "  test                           - Send test notification"
        exit 1
        ;;
esac
