#!/bin/bash
#
# Enhanced Email Notification System for Quantum AI Trading Bot
# Provides multiple notification options and frequencies
#

set -euo pipefail

# Configuration
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV="/home/davidsanker/venv/bin/activate"
PYTHON="/home/davidsanker/venv/bin/python3"
REPORTER_SCRIPT="/home/davidsanker/quantum-trading-bot-new/bin/quantum_daily_reporter.py"
LOG_FILE="/home/davidsanker/platform/logs/enhanced_email_notifications.log"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Logging function
log() {
    echo -e "${GREEN}[$(date '+%Y-%m-%d %H:%M:%S')]${NC} $*" | tee -a "$LOG_FILE"
}

error() {
    echo -e "${RED}[$(date '+%Y-%m-%d %H:%M:%S')] ERROR:${NC} $*" | tee -a "$LOG_FILE"
}

# Send immediate notification
send_immediate_notification() {
    local subject=$1
    local message=$2

    log "📧 Sending immediate notification: $subject"

    source "$VENV"
    cat <<'PYEOF' | $PYTHON
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart

subject = "$subject"
message = "$message"

smtp_server = "smtp.1und1.de"
smtp_port = 587
sender_email = "david@sanker.at"
sender_password = "YOUR_SMTP_PASSWORD"
recipients = ["david@sanker.at", "miriam.sanker@gmail.com"]

msg = MIMEMultipart()
msg['From'] = sender_email
msg['To'] = ", ".join(recipients)
msg['Subject'] = f"🤖 Quantum AI Bot: {subject}"

body = f"""
<html>
<body>
    <h2>{subject}</h2>
    <p>{message}</p>
    <hr>
    <p><small>Sent by Quantum AI Trading Bot at {__import__('datetime').datetime.now().strftime('%Y-%m-%d %H:%M:%S')}</small></p>
</body>
</html>
"""

msg.attach(MIMEText(body, 'html'))

server = smtplib.SMTP(smtp_server, smtp_port)
server.starttls()
server.login(sender_email, sender_password)
server.sendmail(sender_email, recipients, msg.as_string())
server.quit()

print("✅ Immediate notification sent successfully")
PYEOF
}

# Send daily summary report
send_daily_summary() {
    log "📊 Sending daily summary report..."

    source "$VENV"
    if [ -f "$REPORTER_SCRIPT" ]; then
        $PYTHON "$REPORTER_SCRIPT"
    else
        error "Reporter script not found: $REPORTER_SCRIPT"
        return 1
    fi
}

